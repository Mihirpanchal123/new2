// Downloads animated 3D Pokémon models (.glb) for every species + Mega form in data.js
// from the Pokémon 3D API asset repo (https://github.com/Pokemon-3D-api/assets),
// plus three.js r170 and the add-ons the game needs (glTF/Draco loaders, bloom).
// Writes ../models.js  — Usage: node tools/build-models.mjs
import fs from 'node:fs/promises';
import path from 'node:path';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const CACHE = path.join(ROOT, 'tools', '.cache');
const ASSETS = 'https://raw.githubusercontent.com/Pokemon-3D-api/assets/main/models/opt';
const THREE_CDN = 'https://cdn.jsdelivr.net/npm/three@0.170.0';
// ES-module add-ons; their own imports are followed and downloaded too
const LIB_ENTRIES = [
  'build/three.module.min.js',
  'examples/jsm/loaders/GLTFLoader.js',
  'examples/jsm/loaders/DRACOLoader.js',
  'examples/jsm/utils/SkeletonUtils.js',
  'examples/jsm/postprocessing/EffectComposer.js',
  'examples/jsm/postprocessing/RenderPass.js',
  'examples/jsm/postprocessing/UnrealBloomPass.js',
  'examples/jsm/postprocessing/OutputPass.js'
];
const LIB_FILES = ['examples/jsm/libs/draco/gltf/draco_decoder.js', 'examples/jsm/libs/draco/gltf/draco_decoder.wasm', 'examples/jsm/libs/draco/gltf/draco_wasm_wrapper.js'];
const libDest = p => path.join(ROOT, 'lib', p.replace(/^examples\/jsm\//, 'addons/').replace(/^build\//, ''));

async function fetchBuf(url) {
  for (let i = 1; ; i++) {
    try {
      const r = await fetch(url);
      if (r.status === 404) return null;
      if (!r.ok) throw new Error(r.status + ' ' + url);
      return Buffer.from(await r.arrayBuffer());
    } catch (e) { if (i >= 4) throw e; await new Promise(r => setTimeout(r, 600 * i)); }
  }
}
async function exists(f) { try { await fs.access(f); return true; } catch { return false; } }

// glTF animation clip names, read straight from the .glb JSON chunk
function clipNames(buf) {
  const len = buf.readUInt32LE(12);
  const json = JSON.parse(buf.slice(20, 20 + len).toString());
  return (json.animations || []).map(a => a.name || '');
}

async function main() {
  // three.js r170 + add-ons (follow relative imports)
  const queue = [...LIB_ENTRIES], seen = new Set();
  while (queue.length) {
    const lib = queue.shift();
    if (seen.has(lib)) continue;
    seen.add(lib);
    const dest = libDest(lib);
    let buf = (await exists(dest)) ? await fs.readFile(dest) : await fetchBuf(`${THREE_CDN}/${lib}`);
    if (!buf) throw new Error('missing lib ' + lib);
    await fs.mkdir(path.dirname(dest), { recursive: true });
    await fs.writeFile(dest, buf);
    if (lib.endsWith('.js')) for (const m of buf.toString().matchAll(/from\s+['"](\.{1,2}\/[^'"]+)['"]/g))
      queue.push(path.posix.normalize(path.posix.join(path.posix.dirname(lib), m[1])));
  }
  for (const f of LIB_FILES) {
    const dest = libDest(f);
    if (await exists(dest)) continue;
    await fs.mkdir(path.dirname(dest), { recursive: true });
    await fs.writeFile(dest, await fetchBuf(`${THREE_CDN}/${f}`));
  }

  const ctx = { window: {} };
  vm.runInNewContext(await fs.readFile(path.join(ROOT, 'data.js'), 'utf8'), ctx);
  const DEX = ctx.window.POKEDEX;
  await fs.mkdir(path.join(ROOT, 'models'), { recursive: true });

  const jobs = [];
  for (const name of DEX.order) {
    const s = DEX.species[name];
    jobs.push({ key: name, id: s.id, candidates: [`regular/${s.id}.glb`] });
    for (const m of s.megas) {
      const z = m.name.endsWith('-mega-z'), x = m.name.endsWith('-mega-x'), y = m.name.endsWith('-mega-y');
      const c = z ? [`za/${s.id}.glb`] : x ? [`x/${s.id}.glb`] : y ? [`y/${s.id}.glb`] : [`mega/${s.id}.glb`];
      jobs.push({ key: m.name, id: s.id, candidates: c });
    }
  }

  const out = {}, missing = [];
  let i = 0;
  await Promise.all(Array.from({ length: 6 }, async () => {
    while (i < jobs.length) {
      const job = jobs[i++];
      // height in metres from the cached PokéAPI response (written by build-data.mjs)
      let height = 1;
      try {
        const p = JSON.parse(await fs.readFile(path.join(CACHE, `_pokemon_${job.key}.json`), 'utf8'));
        height = p.height / 10;
      } catch {}
      let file = null, clips = [];
      for (const c of job.candidates) {
        const dest = path.join(ROOT, 'models', c.replace('/', '-'));
        let buf = (await exists(dest)) ? await fs.readFile(dest) : await fetchBuf(`${ASSETS}/${c}`);
        if (!buf) continue;
        await fs.writeFile(dest, buf);
        file = 'models/' + c.replace('/', '-');
        clips = clipNames(buf);
        break;
      }
      if (!file) missing.push(job.key);
      out[job.key] = { file, height, clips };
    }
  }));

  await fs.writeFile(path.join(ROOT, 'models.js'),
    '// Generated by tools/build-models.mjs — 3D models from the Pokémon 3D API (fan project, non-commercial).\nwindow.MODELS = ' + JSON.stringify(out) + ';\n');
  const have = Object.values(out).filter(m => m.file);
  const animated = have.filter(m => m.clips.length > 3).length;
  console.log(`Models: ${have.length}/${jobs.length} (${animated} with full animation sets). Missing: ${missing.join(', ') || 'none'}`);
}
main().catch(e => { console.error(e); process.exit(1); });
